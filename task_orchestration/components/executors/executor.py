from typing import Any, Mapping, Protocol, TypeVar
from task_orchestration.models import Decision, TaskContext

GoalT = TypeVar("GoalT", contravariant=True)


class Executor(Protocol[GoalT]):
    def apply(self, context: TaskContext, goal: GoalT) -> Decision: ...
    def start(self, context: TaskContext) -> Decision: ...
    def release(self, context: TaskContext) -> None: ...
    def snapshot(self) -> Mapping[str, Any]: ...

